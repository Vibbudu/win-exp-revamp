//! Types shared by every backend crate and mirrored by hand in `app/ui/src/types.ts`.
//! Keep the two files in sync (field names are camelCase on the wire).

use serde::{Deserialize, Serialize};

/// One row of a folder or search-result view.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Entry {
    pub name: String,
    pub path: String,
    pub is_dir: bool,
    /// Bytes. Always 0 for directories.
    pub size: u64,
    /// Unix epoch milliseconds, 0 when unknown.
    pub modified: i64,
    pub created: i64,
    /// Raw Win32 `FILE_ATTRIBUTE_*` bits.
    pub attrs: u32,
    /// Localized shell type name, e.g. "Microsoft Excel Worksheet".
    pub type_name: String,
    /// Lower-case extension without the dot ("" for none / directories).
    pub ext: String,
}

pub const ATTR_READONLY: u32 = 0x1;
pub const ATTR_HIDDEN: u32 = 0x2;
pub const ATTR_SYSTEM: u32 = 0x4;
pub const ATTR_DIRECTORY: u32 = 0x10;
pub const ATTR_REPARSE_POINT: u32 = 0x400;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum SortKey {
    #[default]
    Name,
    Modified,
    Created,
    Type,
    Size,
    Path,
}

#[derive(Clone, Copy, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SortSpec {
    pub key: SortKey,
    pub desc: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ViewInfo {
    pub view_id: u64,
    pub count: u32,
    pub path: String,
    /// Wall-clock time spent producing the view on the backend.
    pub elapsed_ms: f64,
    /// True when a search result set was capped.
    pub truncated: bool,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DriveInfo {
    pub path: String,
    pub label: String,
    pub file_system: String,
    pub total: u64,
    pub free: u64,
    /// "fixed" | "removable" | "network" | "cdrom" | "ram" | "unknown"
    pub kind: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NamedPath {
    pub name: String,
    pub path: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RecentItem {
    pub name: String,
    pub path: String,
    pub is_dir: bool,
    pub accessed: i64,
    pub location: String,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IndexStatus {
    /// "idle" | "loading" | "building" | "ready" | "error"
    pub state: String,
    /// "mft" (elevated, NTFS USN enumeration) | "crawl" | "snapshot"
    pub mode: String,
    pub files: u64,
    pub elapsed_ms: f64,
    pub volumes: Vec<String>,
    pub message: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ArchiveEntry {
    pub name: String,
    pub size: u64,
    pub compressed: u64,
    pub is_dir: bool,
}

/// Everything the preview pane can render. Large binary payloads (images, PDFs, media)
/// are not sent through IPC; the UI loads them from the asset / thumb protocols.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum Preview {
    Image,
    Pdf,
    Video,
    Audio,
    Font,
    /// Shell thumbnail fallback (HEIC, PSD, RAW, Office files with a thumbnail handler, ...).
    Thumbnail { note: String },
    Text { content: String, language: String, truncated: bool },
    /// Pre-sanitized HTML generated by the backend (markdown / docx).
    Html { html: String },
    /// Raw HTML document shown in a script-less sandboxed iframe.
    WebPage { html: String },
    Sheet { sheets: Vec<String>, active: usize, rows: Vec<Vec<String>>, truncated: bool },
    Slides { slides: Vec<Vec<String>> },
    Archive { entries: Vec<ArchiveEntry>, total: usize },
    Folder { items: u64 },
    None { reason: String },
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Property {
    pub label: String,
    pub value: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SystemInfo {
    /// `#rrggbb` accent colour from DWM.
    pub accent: String,
    pub elevated: bool,
    pub user_name: String,
    pub home: String,
}
